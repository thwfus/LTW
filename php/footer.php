                <script defer="" data-name="footer-newsletter">
                  document.addEventListener('DOMContentLoaded', function() {
                    (function(){
                      const newsletterForm = document.getElementById("newsletterForm")
                      const formStatus = document.getElementById("formStatus")

                      if (newsletterForm) {
                        newsletterForm.addEventListener("submit", (e) => {
                          e.preventDefault()

                          const emailInput = newsletterForm.querySelector('input[type="email"]')
                          const emailValue = emailInput.value

                          if (emailValue) {
                            // Visual feedback for successful submission
                            formStatus.textContent = "Thank you for joining our atelier."
                            formStatus.style.color = "#2ecc71" // Success color

                            emailInput.value = ""
                            emailInput.disabled = true
                            newsletterForm.querySelector("button").disabled = true

                            setTimeout(() => {
                              formStatus.style.opacity = "0"
                              setTimeout(() => {
                                formStatus.textContent = ""
                                formStatus.style.opacity = "1"
                                emailInput.disabled = false
                                newsletterForm.querySelector("button").disabled = false
                              }, 500)
                            }, 3000)
                          }
                        })

                        // Real-time validation visual cue
                        const emailInput = newsletterForm.querySelector('input[type="email"]')
                        emailInput.addEventListener("blur", () => {
                          if (emailInput.value && !emailInput.checkValidity()) {
                            formStatus.textContent = "Please enter a valid email address."
                            formStatus.style.color = "#e74c3c" // Error color
                          } else {
                            formStatus.textContent = ""
                          }
                        })
                      }
                    })()
                  });
                </script>
